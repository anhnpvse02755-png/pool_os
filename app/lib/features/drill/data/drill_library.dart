class DrillLibrary {
  static List<Drill> getAllDrills() {
    return [
      ..._beginnerDrills,
      ..._intermediateDrills,
      ..._advancedDrills,
      ..._professionalDrills,
      ..._coachCustomDrills,
    ];
  }

  static List<Drill> getDrillsBySkillLevel(String skillLevel) {
    return getAllDrills().where((d) => d.skillLevel == skillLevel).toList();
  }

  static List<Drill> getDrillsByCategory(String category) {
    return getAllDrills().where((d) => d.category == category).toList();
  }

  static List<Drill> getDrillsByDifficulty(String difficulty) {
    return getAllDrills().where((d) => d.difficulty == difficulty).toList();
  }

  static Drill? getDrillById(int id) {
    try {
      return getAllDrills().firstWhere((d) => d.id == id);
    } catch (_) {
      return null;
    }
  }

  static Drill? getDrillByCode(String code) {
    try {
      return getAllDrills().firstWhere((d) => d.code == code);
    } catch (_) {
      return null;
    }
  }

  static List<Drill> getDrillsBySkill(String skillId) {
    return getAllDrills()
        .where((d) => d.focusSkills.contains(skillId))
        .toList();
  }

  static Map<String, List<Drill>> getDrillsGroupedBySkillLevel() {
    final grouped = <String, List<Drill>>{};
    for (final drill in getAllDrills()) {
      grouped.putIfAbsent(drill.skillLevel, () => []).add(drill);
    }
    return grouped;
  }

  static Map<String, List<Drill>> getDrillsGroupedByCategory() {
    final grouped = <String, List<Drill>>{};
    for (final drill in getAllDrills()) {
      grouped.putIfAbsent(drill.category, () => []).add(drill);
    }
    return grouped;
  }

